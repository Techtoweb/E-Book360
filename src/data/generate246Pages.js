import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Read bookData.ts directly to extract CHAPTERS_DATA and structure exactly 246 pages
const bookDataContent = fs.readFileSync(path.join(__dirname, 'bookData.ts'), 'utf-8');

// Parse chapters
const chapterRegex = /{\s*id:\s*(\d+),\s*title:\s*'([^']+)',\s*titleEn:\s*'([^']+)',\s*pagesCount:\s*(\d+),\s*summary:\s*'([^']+)',[\s\S]*?content:\s*`([\s\S]*?)`\s*}/g;

let match;
const parsedChapters = [];
while ((match = chapterRegex.exec(bookDataContent)) !== null) {
  parsedChapters.push({
    id: parseInt(match[1], 10),
    title: match[2],
    titleEn: match[3],
    pagesCount: parseInt(match[4], 10),
    summary: match[5],
    content: match[6]
  });
}

console.log(`Parsed ${parsedChapters.length} chapters.`);

// Distribution to make exactly 246 pages:
// Ch 0 (ভূমিকা): 7 pages (1 - 7)
// Ch 1: 14 pages (8 - 21)
// Ch 2: 18 pages (22 - 39)
// Ch 3: 22 pages (40 - 61)
// Ch 4: 27 pages (62 - 88)
// Ch 5: 23 pages (89 - 111)
// Ch 6: 23 pages (112 - 134)
// Ch 7: 29 pages (135 - 163)
// Ch 8: 23 pages (164 - 186)
// Ch 9: 22 pages (187 - 208)
// Ch 10: 38 pages (209 - 246)
// Total = 7 + 14 + 18 + 22 + 27 + 23 + 23 + 29 + 23 + 22 + 38 = 246 pages

const pageAllocations = [
  { id: 0, count: 7, start: 1 },
  { id: 1, count: 14, start: 8 },
  { id: 2, count: 18, start: 22 },
  { id: 3, count: 22, start: 40 },
  { id: 4, count: 27, start: 62 },
  { id: 5, count: 23, start: 89 },
  { id: 6, count: 23, start: 112 },
  { id: 7, count: 29, start: 135 },
  { id: 8, count: 23, start: 164 },
  { id: 9, count: 22, start: 187 },
  { id: 10, count: 38, start: 209 },
];

const all246Pages = [];

pageAllocations.forEach(alloc => {
  const chapter = parsedChapters.find(c => c.id === alloc.id) || parsedChapters[0];
  const sections = chapter.content
    .split(/\n---\n|\n(?=## )|\n(?=# )/)
    .map(s => s.trim())
    .filter(s => s.length > 0);

  // Divide sections into alloc.count pages
  const itemsPerPage = Math.max(1, Math.ceil(sections.length / alloc.count));
  
  for (let i = 0; i < alloc.count; i++) {
    const pageNum = alloc.start + i;
    const startIdx = Math.floor((i * sections.length) / alloc.count);
    const endIdx = Math.floor(((i + 1) * sections.length) / alloc.count);
    let pageSections = sections.slice(startIdx, Math.max(startIdx + 1, endIdx));
    if (pageSections.length === 0) {
      pageSections = [sections[sections.length - 1] || chapter.summary];
    }
    
    let combinedContent = pageSections.join('\n\n');
    let pageTitle = `${chapter.title} — অংশ ${i + 1}`;
    
    // Extract first header as page title if available
    const firstLine = pageSections[0].split('\n')[0].replace(/^[#\s]+/, '').trim();
    if (firstLine && firstLine.length < 70) {
      pageTitle = firstLine;
    }

    all246Pages.push({
      pageNumber: pageNum,
      chapterId: chapter.id,
      chapterTitle: chapter.title,
      title: pageTitle,
      content: combinedContent,
      highlights: [
        `অধ্যায়: ${chapter.titleEn}`,
        `পৃষ্ঠা নম্বর: ${pageNum} / 246`,
        `বিষয়বস্তু: ${chapter.summary.slice(0, 80)}...`
      ]
    });
  }
});

console.log(`Generated ${all246Pages.length} total pages.`);

// Write src/data/pdfPages.ts
const outputCode = `// Autogenerated 246 Pages for E-Commerce 360° PDF
export interface PdfPage {
  pageNumber: number;
  chapterId: number;
  chapterTitle: string;
  title: string;
  content: string;
  highlights?: string[];
}

export const TOTAL_PDF_PAGES = ${all246Pages.length};

export const PDF_PAGES_DATA: PdfPage[] = ${JSON.stringify(all246Pages, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, 'pdfPages.ts'), outputCode, 'utf-8');
console.log("Successfully written src/data/pdfPages.ts with 246 pages!");
