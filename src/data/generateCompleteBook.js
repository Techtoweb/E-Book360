// Helper to chunk chapter text into formatted pages
function paginateChapter(chapter, totalPagesForChap) {
  const lines = chapter.fullText.split('\n');
  const pages = [];
  const linesPerPage = Math.max(12, Math.ceil(lines.length / totalPagesForChap));
  
  for (let i = 0; i < totalPagesForChap; i++) {
    const pageNum = chapter.startPage + i;
    const startIdx = i * linesPerPage;
    const endIdx = Math.min(lines.length, (i + 1) * linesPerPage);
    let pageContent = lines.slice(startIdx, endIdx).join('\n').trim();
    
    // If empty for some reason, provide summary section
    if (!pageContent) {
      pageContent = `## ${chapter.title}\n\n${chapter.summary}\n\n*চলমান পৃষ্ঠা ${pageNum}...*`;
    }

    // Determine sub-title for the page
    const firstHeadingMatch = pageContent.match(/^(?:#|##|###)\s*(.+)$/m);
    const subTitle = firstHeadingMatch 
      ? firstHeadingMatch[1].replace(/[*#]/g, '').trim() 
      : `${chapter.title} (পর্ব ${i + 1})`;

    pages.push({
      pageNumber: pageNum,
      chapterId: chapter.id,
      chapterTitle: chapter.title,
      title: subTitle,
      content: pageContent,
      highlights: chapter.highlights ? chapter.highlights.slice(0, 3) : []
    });
  }
  return pages;
}

